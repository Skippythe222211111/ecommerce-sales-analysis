-- Load source rows into retail.online_retail_raw before running 01_analysis.sql.
-- Exact duplicates are retained in raw and removed only in the analysis view.
CREATE SCHEMA IF NOT EXISTS retail;

CREATE TABLE IF NOT EXISTS retail.online_retail_raw (
    source_row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no TEXT,
    stock_code TEXT,
    description TEXT,
    quantity NUMERIC(18, 4),
    invoice_date TIMESTAMP,
    unit_price NUMERIC(18, 4),
    customer_id BIGINT,
    country TEXT
);

CREATE OR REPLACE VIEW retail.online_retail_clean AS
WITH ranked AS (
    SELECT
        source_row_id,
        invoice_no,
        stock_code,
        description,
        quantity,
        invoice_date,
        unit_price,
        customer_id,
        country,
        ROW_NUMBER() OVER (
            PARTITION BY invoice_no, stock_code, description, quantity,
                         invoice_date, unit_price, customer_id, country
            ORDER BY source_row_id
        ) AS duplicate_rank
    FROM retail.online_retail_raw
)
SELECT
    source_row_id,
    invoice_no,
    stock_code,
    description,
    quantity,
    invoice_date,
    unit_price,
    customer_id,
    country,
    quantity * unit_price AS line_value,
    CASE
        WHEN invoice_no ILIKE 'C%' THEN 'cancellation'
        WHEN quantity < 0 AND invoice_no IS NOT NULL AND invoice_date IS NOT NULL
            THEN 'return_or_adjustment'
        WHEN quantity = 0 THEN 'zero_quantity'
        WHEN unit_price <= 0 THEN 'nonpositive_price'
        WHEN quantity > 0 AND unit_price > 0
             AND invoice_no IS NOT NULL AND invoice_date IS NOT NULL
            THEN 'sale'
        ELSE 'invalid_transaction'
    END AS line_type
FROM ranked
WHERE duplicate_rank = 1;
